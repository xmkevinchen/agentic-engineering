// Build step: compile the frozen schemas to Ajv standalone ESM modules.
//
// This runs at build time only. The generated module is checked in, and the Gate
// runtime imports it directly — no `npm install`, no dependency resolution and no
// schema compilation on the runtime path.
//
//   node plugins/ae/tests/foundation/build/build-validators.mjs
//   node plugins/ae/tests/foundation/build/build-validators.mjs --check
//
// `--check` regenerates into memory and diffs against the checked-in bytes; it
// is how "regeneration is byte-identical" is asserted when the toolchain is
// present.

// Draft 2020-12 entry point, not the package default (draft-07). The dialect is
// part of the freeze: `$defs`/`unevaluatedProperties` behave differently across
// drafts, and v1 authoritative schemas declare 2020-12.
import Ajv from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { vendorRuntime } from './vendor-runtime.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const NODE_MODULES = join(HERE, 'node_modules');
const VALIDATOR_DIR = join(HERE, '..', '..', 'fixtures', 'v1-foundation', 'validator');
// The generated validator is not fixture data. It is a mechanism dependency: the
// in-process release provider validates manifests with it, and the tree that gets
// promoted into the runtime cannot import a module out of tests/fixtures/. The
// schema stays with the corpus; only the compiled output lands in lib/.
const VALIDATOR_OUT_DIR = join(HERE, '..', 'lib');

const TARGETS = [
  { schema: 'release-manifest-v1.schema.json', output: 'release-manifest-v1.validator.mjs', exportName: 'validateReleaseManifest' },
];

function generate(schemaFile, exportName) {
  const schema = JSON.parse(readFileSync(join(VALIDATOR_DIR, schemaFile), 'utf8'));
  const ajv = new Ajv({
    // Closed by construction: the schemas say additionalProperties:false, and
    // strict mode refuses to compile a schema that quietly ignores a keyword.
    strict: true,
    allErrors: true,
    // Deterministic output: no run-time option may change the generated bytes.
    code: { source: true, esm: true, optimize: 1, lines: true },
  });
  ajv.addSchema(schema, exportName);
  const generated = standaloneCode(ajv, { [exportName]: exportName });
  const { code, vendored } = vendorRuntime(generated, NODE_MODULES);
  return { code, vendored: vendored.map((v) => v.moduleId) };
}

const sha = (text) => `sha256:${createHash('sha256').update(Buffer.from(text, 'utf8')).digest('hex')}`;

const checkOnly = process.argv.includes('--check');
const pins = {};
let drift = 0;

for (const target of TARGETS) {
  const { code: generated, vendored } = generate(target.schema, target.exportName);
  const outputPath = join(VALIDATOR_OUT_DIR, target.output);
  if (checkOnly) {
    const existing = readFileSync(outputPath, 'utf8');
    if (existing !== generated) {
      process.stderr.write(`DRIFT ${target.output}: regenerated bytes differ from the checked-in module\n`);
      drift += 1;
    } else {
      process.stdout.write(`ok ${target.output} regenerates byte-identically\n`);
    }
  } else {
    writeFileSync(outputPath, generated);
    process.stdout.write(`wrote ${target.output} (${Buffer.byteLength(generated)} bytes)\n`);
  }
  pins[target.output] = {
    schema_ref: target.schema,
    schema_digest: sha(readFileSync(join(VALIDATOR_DIR, target.schema), 'utf8')),
    validator_digest: sha(generated),
    export_name: target.exportName,
    vendored_runtime: vendored,
  };
}

const lockfile = JSON.parse(readFileSync(join(HERE, 'package-lock.json'), 'utf8'));
const manifest = JSON.parse(readFileSync(join(HERE, 'package.json'), 'utf8'));

const toolchain = {
  schema_version: 'ae.fixture.validator-toolchain.v1',
  node_range: manifest.engines.node,
  json_schema_dialect: 'https://json-schema.org/draft/2020-12/schema',
  ajv_entry_point: 'ajv/dist/2020.js',
  ajv_version: lockfile.packages['node_modules/ajv'].version,
  ajv_integrity: lockfile.packages['node_modules/ajv'].integrity,
  transitive: Object.fromEntries(
    Object.entries(lockfile.packages)
      .filter(([name]) => name.startsWith('node_modules/') && name !== 'node_modules/ajv')
      .map(([name, spec]) => [name.replace('node_modules/', ''), spec.version])
      .sort(([a], [b]) => (a < b ? -1 : 1)),
  ),
  generator_options: {
    strict: true,
    allErrors: true,
    code: { source: true, esm: true, optimize: 1, lines: true },
  },
  outputs: pins,
};

const pinPath = join(VALIDATOR_DIR, 'toolchain-pin.json');
const pinText = `${JSON.stringify(toolchain, null, 2)}\n`;
if (checkOnly) {
  if (readFileSync(pinPath, 'utf8') !== pinText) {
    process.stderr.write('DRIFT toolchain-pin.json: regenerated pin differs from the checked-in pin\n');
    drift += 1;
  } else {
    process.stdout.write('ok toolchain-pin.json regenerates byte-identically\n');
  }
} else {
  writeFileSync(pinPath, pinText);
  process.stdout.write('wrote toolchain-pin.json\n');
}

process.exit(drift === 0 ? 0 : 1);
